"""Ascend C custom operators for HQSB S09 (add / row_reduce_sum / rms_norm).

Layout:

* ``common/hqsb_tiling_data.h`` — the 72-byte host/device TilingData ABI,
  generated by :mod:`hqsb.ascend.tiling`; a test fails if it drifts from the
  generator.  Both the host tiling and the device kernel include this one header.
* ``custom/`` — the operator project, laid out like the official CANN project
  emitted by ``msopgen gen -f aclnn -c ai_core-Ascend310B1 -lan cpp``:
  ``op_host/<op>.cpp`` (op definition, shape/dtype inference, tiling) and
  ``op_kernel/<op>.cpp`` (Ascend C kernel entry).

The kernels are the **naive reference implementations**: they prove the
compile -> load -> run -> numeric-check chain end to end.  They are not
optimised, and no number they produce may be reported as tuned performance.

Build with ``scripts/ascend/build_ascend_ops.sh`` after sourcing the CANN
environment; on a host without CANN the script fails with a clear message
instead of silently producing an artifact.
"""

from __future__ import annotations

__all__ = [
    "PROVIDER_NAME",
    "KERNEL_NAMES",
]

PROVIDER_NAME = "ascend"

#: Kernel names exposed by this provider.  The first two map to E09-02, the
#: third to E09-03/E09-04; see :mod:`hqsb.ascend.operators` for the frozen specs.
KERNEL_NAMES = ("add", "row_reduce_sum", "rms_norm")
